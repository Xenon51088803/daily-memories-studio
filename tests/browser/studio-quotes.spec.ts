import { test, expect } from '@playwright/test';
import { localDay, shiftDay } from '../../src/components/diary/shared';

test('daily quote can be edited inside the studio without exposing private diary',async({page,request})=>{
  const today=localDay();const tomorrow=shiftDay(today);
  const origin='http://127.0.0.1:3311';
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/studio#daily-quote');
  await expect(page.getByRole('button',{name:'每日一句',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(page.getByLabel('每日一句展示日期')).toHaveValue(today);
  await page.getByRole('button',{name:'提前写明天',exact:true}).click();
  await expect(page.getByLabel('每日一句展示日期')).toHaveValue(tomorrow);
  const initial=await(await request.get('/api/studio/quotes?date='+tomorrow)).json();
  const future='STUDIO_FUTURE\n明天也要认真生活。';
  await page.getByLabel('这一天的一句话').fill(future);
  await page.getByRole('button',{name:'保存每日一句',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('已保存明天的每日一句');
  await page.reload();
  await expect(page.getByLabel('每日一句展示日期')).toHaveValue(today);
  await page.getByRole('button',{name:'提前写明天',exact:true}).click();
  await expect(page.getByLabel('这一天的一句话')).toHaveValue(future);
  const privateResult=await request.get('/api/diary?date='+today);
  expect(privateResult.status()).toBe(401);
  const studio=await(await request.get('/api/studio/quotes?date='+tomorrow)).json();
  expect(Object.keys(studio.quote).sort()).toEqual(['date','text','version']);
  const publicBefore=await(await request.get('/api/diary?action=public')).text();
  expect(publicBefore).not.toContain('STUDIO_FUTURE');
  const stale=await request.put('/api/studio/quotes',{headers:{origin,'X-Homepage-Editor':'1'},data:{...initial.quote,text:'stale'}});
  expect(stale.status()).toBe(409);
  const crossOrigin=await request.put('/api/studio/quotes',{headers:{origin:'https://example.com','X-Homepage-Editor':'1'},data:studio.quote});
  expect(crossOrigin.status()).toBe(403);
  await page.getByRole('button',{name:'今天展示',exact:true}).click();
  await expect(page.getByLabel('每日一句展示日期')).toHaveValue(today);
  const multiline='STUDIO_TODAY\n今天也有值得收藏的瞬间。';
  await page.getByLabel('这一天的一句话').fill('STUDIO_TODAY');
  await page.getByLabel('这一天的一句话').press('Enter');
  await page.getByLabel('这一天的一句话').pressSequentially('今天也有值得收藏的瞬间。');
  const preview=page.locator('p').filter({hasText:'STUDIO_TODAY'}).first();
  await expect(preview).toHaveCSS('white-space','pre-wrap');
  expect(await preview.innerText()).toBe(multiline);
  page.once('dialog',dialog=>dialog.dismiss());
  await page.getByRole('button',{name:'首页与关于',exact:true}).click();
  await expect(page.getByRole('button',{name:'每日一句',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(page.getByLabel('这一天的一句话')).toHaveValue(multiline);
  await page.getByRole('button',{name:'保存每日一句',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('本机预览已更新');
  const released=await(await request.get('/api/diary?action=public')).text();
  expect(released).toContain('STUDIO_TODAY');expect(released).not.toContain('STUDIO_FUTURE');
  const past=shiftDay(today,-40);
  const older=await(await request.get('/api/studio/quotes?date='+past)).json();
  const olderSave=await request.put('/api/studio/quotes',{headers:{origin,'X-Homepage-Editor':'1'},data:{...older.quote,text:'往日的片刻'}});
  expect(olderSave.status()).toBe(200);
  const publicPage=await page.context().newPage();
  await publicPage.goto('/');
  for (const selector of ['.letter-content p','.memory-page>p']) {
    await expect(publicPage.locator(selector)).toHaveText(multiline);
    await expect(publicPage.locator(selector)).toHaveCSS('white-space','pre-wrap');
    expect(await publicPage.locator(selector).innerText()).toBe(multiline);
  }
  await publicPage.setViewportSize({width:390,height:844});
  expect(await publicPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await publicPage.getByRole('button',{name:'← 上一条',exact:true}).click();
  await expect(publicPage.locator('.memory-page>p')).toHaveText('往日的片刻');
  await expect(publicPage.getByRole('button',{name:past,exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(publicPage.getByRole('button',{name:'← 上一条',exact:true})).toBeDisabled();
  await publicPage.getByRole('button',{name:'下一条 →',exact:true}).click();
  await expect(publicPage.locator('.memory-page>p')).toHaveText(multiline);
  await publicPage.close();
  // Compiling the home route can refresh the studio in Next development mode.
  await page.getByRole('button',{name:'今天展示',exact:true}).click();
  await expect(page.getByLabel('这一天的一句话')).toHaveValue(multiline);
  await page.screenshot({path:'test-results/studio-quotes-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/studio-quotes-mobile.png',fullPage:true});
  await page.getByLabel('这一天的一句话').fill('');
  await page.getByRole('button',{name:'保存每日一句',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('已清空');
  expect(await(await request.get('/api/diary?action=public')).text()).not.toContain('STUDIO_TODAY');
  expect(errors).toEqual([]);
});
